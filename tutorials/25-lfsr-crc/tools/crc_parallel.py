"""Derive the byte-parallel CRC-32 equations from the bit-serial CRC.

The serial CRC is run for eight steps on symbols instead of bits. Each signal is
a set of input variables, and XOR of two signals is the symmetric difference of
their sets. After eight steps, each state bit is a set: the bits to XOR.

    python3 tools/crc_parallel.py           print the equations
    python3 tools/crc_parallel.py verilog   print rtl/crc32_byte_xor.v

Both check the equations against zlib.crc32 first, and stop if they are wrong.
"""

import random
import sys
import zlib

WIDTH = 32
DATA_BITS = 8
# x^32 + x^26 + x^23 + ... + 1 is 0x04C11DB7 written the usual way. The reflected
# CRC shifts right, so it uses the same polynomial with its bits reversed.
POLY = 0xEDB88320

# A set of variables is an int used as a bitmask: bit i is c[i], the current
# state, and bit WIDTH + j is d[j], the data byte.
def c(i):
    return 1 << i


def d(j):
    return 1 << (WIDTH + j)


def serial_step(state, bit):
    """One clock of rtl/crc32_serial.v, on sets. state[i] is the set for bit i."""
    feedback = state[0] ^ bit
    nxt = state[1:] + [0]  # shift right: bit i takes bit i + 1, and 0 comes in at the top
    for i in range(WIDTH):
        if (POLY >> i) & 1:
            nxt[i] ^= feedback
    return nxt


def derive():
    state = [c(i) for i in range(WIDTH)]
    for j in range(DATA_BITS):  # reflected: bit 0 of the byte goes first
        state = serial_step(state, d(j))
    return state


def names(eq):
    """The variables in a set, in the order state[0] ... state[31], data[0] ... data[7]."""
    out = [f"state[{i}]" for i in range(WIDTH) if (eq >> i) & 1]
    out += [f"data[{j}]" for j in range(DATA_BITS) if (eq >> (WIDTH + j)) & 1]
    return out


def apply(eqs, state, byte):
    """Evaluate the equations: each new bit is the parity of the chosen inputs."""
    inputs = state | (byte << WIDTH)
    return sum((bin(eq & inputs).count("1") & 1) << i for i, eq in enumerate(eqs))


def crc32(eqs, message):
    state = 0xFFFFFFFF
    for byte in message:
        state = apply(eqs, state, byte)
    return state ^ 0xFFFFFFFF


def check(eqs):
    rng = random.Random(24)
    messages = [b"", b"123456789"]
    messages += [rng.randbytes(rng.randrange(1, 200)) for _ in range(1000)]
    for message in messages:
        if crc32(eqs, message) != zlib.crc32(message):
            sys.exit(f"equations disagree with zlib.crc32 on {message!r}")
    print(f"checked against zlib.crc32 on {len(messages)} messages", file=sys.stderr)


def table(eqs):
    for i, eq in enumerate(eqs):
        print(f"next[{i:2}] = " + " ^ ".join(names(eq)))
    terms = [bin(eq).count("1") for eq in eqs]
    print(f"inputs per bit: {min(terms)} to {max(terms)}, {sum(terms)} in all")


def verilog(eqs):
    lines = [
        "// Generated by tools/crc_parallel.py. Do not edit: run it again instead.",
        "// The same CRC-32 as crc32_byte.v, written as one XOR per state bit.",
        "module crc32_byte_xor (",
        "    input  wire        clk,",
        "    input  wire        rst,",
        "    input  wire        clear,",
        "    input  wire        valid,",
        "    input  wire [7:0]  data,",
        "    output wire [31:0] crc",
        ");",
        "",
        "    reg  [31:0] state;",
        "    wire [31:0] next;",
        "",
    ]
    for i, eq in enumerate(eqs):
        lines.append(f"    assign next[{i}] = " + " ^ ".join(names(eq)) + ";")
    lines += [
        "",
        "    always @(posedge clk) begin",
        "        if (rst || clear)",
        "            state <= 32'hFFFFFFFF;",
        "        else if (valid)",
        "            state <= next;",
        "    end",
        "",
        "    assign crc = ~state;",
        "",
        "endmodule",
    ]
    print("\n".join(lines))


def main():
    eqs = derive()
    check(eqs)
    if sys.argv[1:] == ["verilog"]:
        verilog(eqs)
    elif sys.argv[1:] == []:
        table(eqs)
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
