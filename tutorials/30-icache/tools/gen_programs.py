#!/usr/bin/env python3
"""Writes the two long programs that would be tedious to type: straight-line
code, and a loop bigger than most of the caches measured.

    python3 tools/gen_programs.py build/

    straight.asm   STRAIGHT ALU instructions, each run once, then a check
    bigloop.asm    a loop of BODY ALU instructions, run ITERATIONS times, then a check

The instructions cycle through four kinds that depend on each other, so a
fetch of the wrong word changes the answer:

    addi a0, a0, k      xori a1, a1, k      add a2, a2, a0      sub a3, a3, a1

Python works out what the four registers must hold at the end, and the program
compares them. It ends with ebreak if all four are right, and with ecall if
not. Like every program here it uses only branches relative to pc, so it runs
from RAM and from the flash alike.
"""

import os
import sys

STRAIGHT = 512        # instructions: 2 KiB of code
BODY = 384            # instructions in the big loop's body: 1.5 KiB
ITERATIONS = 4
MASK = 0xFFFFFFFF
REGS = ("a0", "a1", "a2", "a3")


def instructions(count):
    """count instructions, as (kind, k) pairs."""
    return [(n % 4, (n * 37) % 2048 - 1024) for n in range(count)]


def text(ops):
    names = ["addi   a0, a0, {k}", "xori   a1, a1, {k}", "add    a2, a2, a0", "sub    a3, a3, a1"]
    return ["        " + names[kind].format(k=k) for kind, k in ops]


def run(ops, regs):
    """What the instructions do to the four registers."""
    for kind, k in ops:
        if kind == 0:
            regs["a0"] = (regs["a0"] + k) & MASK
        elif kind == 1:
            regs["a1"] = (regs["a1"] ^ k) & MASK
        elif kind == 2:
            regs["a2"] = (regs["a2"] + regs["a0"]) & MASK
        else:
            regs["a3"] = (regs["a3"] - regs["a1"]) & MASK


def start():
    return [f"        li     {name}, 0" for name in REGS]


def check(regs):
    lines = []
    for name in REGS:
        lines.append(f"        li     t0, {regs[name]:#x}")
        lines.append(f"        bne    {name}, t0, fail")
    return lines + ["        ebreak", "fail:   ecall"]


def straight():
    ops = instructions(STRAIGHT)
    regs = dict.fromkeys(REGS, 0)
    run(ops, regs)
    return ([f"# Generated by tools/gen_programs.py: {STRAIGHT} instructions of straight-line code."]
            + start() + text(ops) + check(regs))


def bigloop():
    ops = instructions(BODY)
    regs = dict.fromkeys(REGS, 0)
    for _ in range(ITERATIONS):
        run(ops, regs)
    return ([f"# Generated by tools/gen_programs.py: a loop of {BODY} instructions, "
             f"run {ITERATIONS} times."]
            + start() + [f"        li     s0, {ITERATIONS}", "loop:"] + text(ops)
            + ["        addi   s0, s0, -1", "        bnez   s0, loop"] + check(regs))


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "build"
    for name, lines in (("straight", straight()), ("bigloop", bigloop())):
        path = os.path.join(out, f"{name}.asm")
        with open(path, "w") as file:
            file.write("\n".join(lines) + "\n")
        print(f"{path}: {len(lines)} lines")


if __name__ == "__main__":
    main()
