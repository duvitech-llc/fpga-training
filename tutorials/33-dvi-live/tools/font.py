#!/usr/bin/env python3
"""A 5 by 7 pixel font, drawn here by hand, for the characters the demo needs.

The C program and the Python model of the picture both take their glyphs from
this file, so the model cannot disagree with the program about a letter:

    python3 tools/font.py build/font.h     writes the table for C

Each glyph is 7 rows. In the C table each row is a byte, the leftmost pixel in
bit 4. Characters not listed here draw nothing.
"""

